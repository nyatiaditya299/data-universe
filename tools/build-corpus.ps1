# Builds Beta/corpus.js (the starter library for "Ask the archive") from files in Source_Documents.
# Only files whose contents were checked against their names are listed here. Re-run after adding files:
#   powershell -ExecutionPolicy Bypass -File tools/build-corpus.ps1
$root = Split-Path $PSScriptRoot -Parent
$src = Join-Path $root 'Source_Documents\Fisher_Investments'

# id, file, title, date (yyyy-mm-dd or '' if undated), kind, publisher
$manifest = @(
  @('cares-act',        '2020-cares-act-congress.md',               'H.R.748 CARES Act (Congress.gov record)',                         '2020-03-27', 'Government record',  'Congress.gov'),
  @('bls-cpi-aug-2022', '2022-09-13-bls-cpi-release.md',            'Consumer Price Index, August 2022 (BLS news release)',            '2022-09-13', 'Government release', 'US Bureau of Labor Statistics'),
  @('fdic-svb',         '2023-03-10-fdic-svb-closure.md',           'FDIC creates Deposit Insurance National Bank of Santa Clara (SVB)','2023-03-10', 'Government release', 'FDIC'),
  @('fdic-signature',   '2023-03-12-fdic-signature-bridge-bank.md', 'FDIC establishes Signature Bridge Bank',                          '2023-03-12', 'Government release', 'FDIC'),
  @('fed-btfp',         '2023-03-12-federal-reserve-btfp.md',       'Federal Reserve announces Bank Term Funding Program',             '2023-03-12', 'Government release', 'Federal Reserve Board'),
  @('fisher-top-down',  'fisher-public-top-down-process.md',        'Fisher Investments: Top-Down Investment Process',                 '',           'Firm process',       'Fisher Investments'),
  @('fisher-form-crs',  'Fisher_Form_CRS_2026_extracted.md',        'Fisher Investments Form CRS (Client Relationship Summary)',       '2026-02-12', 'Regulatory filing',  'Fisher Investments / SEC')
)

$docs = foreach ($m in $manifest) {
  $raw = [IO.File]::ReadAllText((Join-Path $src $m[1]), [Text.Encoding]::UTF8)
  $url = ''
  if ($raw -match '(?m)^(?:Original URL|URL):\s*(\S+)') { $url = $Matches[1] }
  # Drop the snapshot header lines; the page cleans links and menus when it indexes.
  $body = ($raw -split "`n" | Where-Object { $_ -notmatch '^(Original URL|URL):' }) -join "`n"
  [ordered]@{ id = $m[0]; title = $m[2]; date = $m[3]; kind = $m[4]; publisher = $m[5]; url = $url; file = "Source_Documents/Fisher_Investments/$($m[1])"; text = $body }
}

$json = ConvertTo-Json @($docs) -Depth 4
$out = "// Generated by tools/build-corpus.ps1 from Source_Documents. Do not edit by hand.`nexport const STARTER_DOCS = $json;`n"
[IO.File]::WriteAllText((Join-Path $root 'Beta\corpus.js'), $out, (New-Object Text.UTF8Encoding $false))
"Wrote Beta/corpus.js with $(@($docs).Count) documents"
